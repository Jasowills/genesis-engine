//! Throwaway probe helper: expose the *exact resolved* wgpu version from
//! Cargo.lock to the binary at compile time. wgpu 30 no longer exports a
//! `VERSION` constant, and reading the lockfile avoids hardcoding a number
//! that could silently drift from what is actually built.

use std::{env, fs, path::PathBuf};

fn main() {
    let lock = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap()).join("Cargo.lock");
    let text = fs::read_to_string(&lock).expect("Cargo.lock must exist (generated by cargo)");

    let mut in_wgpu = false;
    let mut version: Option<String> = None;
    for line in text.lines() {
        if line.trim() == "[[package]]" {
            in_wgpu = false;
            continue;
        }
        if line.trim() == "name = \"wgpu\"" {
            in_wgpu = true;
            continue;
        }
        if in_wgpu && let Some(v) = line.trim().strip_prefix("version = ") {
            version = Some(v.trim_matches('"').to_string());
            break;
        }
    }

    let version = version.expect("wgpu package not found in Cargo.lock");
    println!("cargo:rustc-env=PROBE_WGPU_VERSION={}", version);
    println!("cargo:rerun-if-changed=Cargo.lock");
}
